"""Drop the reproduced-on-demand negative-result bytes (extracted PDF rasters and
contact sheets) while keeping the index, so the repo does not carry 26 MB of
trade-show photography. Everything removed is regenerated by pdf_images.py +
pdf_sheets.py in seconds. The decoded FAQ images, Caragublu originals and wiki
revisions are KEPT: they are real recovered evidence.
"""
import os
import shutil
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
HERE = os.path.dirname(os.path.abspath(__file__))


def size(p):
    t = 0
    for root, d, files in os.walk(p):
        for f in files:
            t += os.path.getsize(os.path.join(root, f))
    return t


for sub in ("pdfimg", "pdfsheets"):
    p = os.path.join(HERE, sub)
    if not os.path.isdir(p):
        continue
    before = size(p)
    shutil.rmtree(p)
    print("removed %-10s %6.1f MB" % (sub, before / 1048576))

tot = size(HERE)
print("\n_swipe now: %.1f MB" % (tot / 1048576))
for sub in sorted(os.listdir(HERE)):
    p = os.path.join(HERE, sub)
    if os.path.isdir(p):
        n = sum(len(f) for _, _, f in os.walk(p))
        print("  %-12s %7.2f MB  %d files" % (sub, size(p) / 1048576, n))
    else:
        print("  %-12s %7.2f MB" % (sub, os.path.getsize(p) / 1048576))
